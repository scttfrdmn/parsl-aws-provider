"""CurveZMQ certificate distribution (#62).

These tests use real certificates, generated by pyzmq into ``tmp_path``, rather
than fixtures with plausible-looking strings. The reason is that the defect class
here is "the worker cannot use what we shipped", and only real key material
proves otherwise -- a test that ships ``b"fake"`` and asserts ``b"fake"`` arrives
would pass against a distributor that shipped the wrong *files*.

The one behaviour these cannot cover is a live SecureString round-trip and an
instance-profile fetch; that is in ``tests/aws/test_curvezmq_e2e.py``.

SPDX-License-Identifier: Apache-2.0
SPDX-FileCopyrightText: 2025-2026 Scott Friedman and Project Contributors
"""

